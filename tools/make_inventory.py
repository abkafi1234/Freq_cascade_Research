#!/usr/bin/env python3
"""Regenerate the experiment inventory table inside EXPERIMENTS.md.

Every number in that table is computed here from the files in ``results/``; the
prose around it is written by hand. The mapping from a result file to the paper
element it supports is read from ``SI/README.md`` (itself generated by
``tools/make_si.py``), so the two cannot drift apart.

The script fails if a result file has no entry in PRODUCER below. That is the
point: a new experiment cannot be added to this repository without being
documented.

    python tools/make_inventory.py            # rewrite the table in EXPERIMENTS.md
    python tools/make_inventory.py --print    # print it instead
"""

