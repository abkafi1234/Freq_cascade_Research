def si_map() -> dict:
    """jsonl name -> (SI file, the paper element that SI file backs)."""
    text = (ROOT / "SI" / "README.md").read_text(encoding="utf-8")
    backs = {}
    for m in re.finditer(r"^\| `(SI\d+_[^`]+\.csv)` \|[^|]*\|[^|]*\|[^|]*\|[^|]*\| (.+?) \|$",
                         text, flags=re.M):
        backs[m.group(1)] = m.group(2).strip()
    out = {}
    for m in re.finditer(r"^- \*\*(SI\d+_[^*]+\.csv)\*\* <- (.+?)\.?$", text, flags=re.M):
        si, srcs = m.group(1), m.group(2)
        for src in re.findall(r"`([^`]+\.jsonl)`", srcs):
            out[src] = (si, backs.get(si, ""))
    return out


def scan(path: Path):
    """(rows, rows carrying an error field) for a JSONL file."""
    rows = errs = 0
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rows += 1
        rec = json.loads(line)
        if rec.get("error"):
            errs += 1
    return rows, errs


def table() -> str:
    si = si_map()
    unmapped = []
    lines = ["| result file | rows | error rows | written by | supporting data | backs |",
             "|---|---:|---:|---|---|---|"]
    for f in sorted(RESULTS.glob("*.jsonl")) + sorted(RESULTS.glob("*.json")):
        name = f.name
        if name not in PRODUCER:
            unmapped.append(name)
            continue
        if f.suffix == ".jsonl":
            rows, errs = scan(f)
        else:
            rows, errs = len(json.loads(f.read_text(encoding="utf-8"))), 0
        s, b = si.get(name, ("--", NOT_IN_SI.get(name, "")))
        lines.append(f"| `{name}` | {rows} | {errs} | `{PRODUCER[name]}` | "
                     f"{('`' + s + '`') if s != '--' else '--'} | {b} |")
    if unmapped:
        raise SystemExit("undocumented result files (add them to PRODUCER): "
                         + ", ".join(unmapped))

    lines += ["", "### Superseded and discarded runs, kept for the record", "",
              "| directory | files | rows | what it is |", "|---|---:|---:|---|"]
    for d, why in sorted(SUPERSEDED.items()):
        files = sorted((RESULTS / d).glob("*.jsonl"))
        rows = sum(scan(x)[0] for x in files)
        lines.append(f"| `results/{d}/` | {len(files)} | {rows} | {why} |")

    n_files = len(list(RESULTS.rglob("*.jsonl")))
    total_rows = sum(scan(f)[0] for f in RESULTS.rglob("*.jsonl"))
    total_bytes = sum(f.stat().st_size for f in RESULTS.rglob("*") if f.is_file())
    lines += ["", f"Totals: {n_files} JSONL files, {total_rows} rows, "
                 f"{total_bytes / 1e6:.1f} MB. Generated by `tools/make_inventory.py` on "
                 f"{dt.date.today().isoformat()}."]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true", dest="show")
    a = ap.parse_args()
    body = table()
    if a.show:
        print(body)
        return
    doc = ROOT / "EXPERIMENTS.md"
    text = doc.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"markers {BEGIN} / {END} not found in {doc}")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    doc.write_text(f"{head}{BEGIN}\n\n{body}\n\n{END}{tail}", encoding="utf-8")
    print(f"rewrote the inventory table in {doc}")


if __name__ == "__main__":
    main()
